//! G-code for 3D printers: the pictures a slicer stores in it (the plate as
//! it will print) and what it says of the print. As text (`PrusaSlicer`,
//! Orca, Bambu Studio, Cura), both are comments: pictures as base64 between
//! `; thumbnail begin W×H length` and `; thumbnail end`, near the start, and
//! facts as `; key = value` at the start and the end. As Prusa's binary
//! G-code (`.bgcode`, read from its published specification), both are
//! blocks before the first block of G-code.
use crate::Found;
use base64::Engine as _;
use bibli_core::CancelToken;
use bibli_platform::inspection::{self, limits};
use std::io::{Read, Seek, SeekFrom};
use std::path::Path;

/// The end of a text file read for the facts slicers write last.
const TAIL: u64 = 256 * 1024;

/// What a slicer says of the print, gathered from its comments or its
/// binary file's metadata, whichever words it uses.
#[derive(Default)]
struct Facts {
    slicer: Option<String>,
    time: Option<String>,
    grams: Option<String>,
    length: Option<String>,
    layer_height: Option<String>,
    layers: Option<String>,
    printer: Option<String>,
    material: Option<String>,
}

/// A list of numbers (one per extruder, `1.5, 0.25`) as their sum.
fn sum(value: &str) -> Option<f64> {
    value
        .split(',')
        .map(|n| n.trim().trim_end_matches('m').parse::<f64>().ok())
        .sum()
}

/// A number of seconds as a slicer would say it.
pub(crate) fn duration(seconds: f64) -> String {
    let seconds = seconds.max(0.).round() as u64;
    let (h, m, s) = (seconds / 3600, seconds / 60 % 60, seconds % 60);
    match (h, m) {
        (0, 0) => format!("{s}s"),
        (0, _) => format!("{m}m {s}s"),
        _ => format!("{h}h {m}m {s}s"),
    }
}

/// A number written with as few decimals as it needs, at most two.
pub(crate) fn short(n: f64) -> String {
    let text = format!("{n:.2}");
    text.trim_end_matches('0').trim_end_matches('.').to_owned()
}

impl Facts {
    /// One `key = value` (or `key: value`) a slicer wrote; the first said
    /// of a fact is kept.
    fn note(&mut self, key: &str, value: &str) {
        let key = key.trim().to_ascii_lowercase();
        let value = value.trim();
        if value.is_empty() {
            return;
        }
        let keep = |slot: &mut Option<String>, value: Option<String>| {
            if slot.is_none() {
                *slot = value;
            }
        };
        match key.as_str() {
            "producer" => keep(&mut self.slicer, Some(value.to_owned())),
            "estimated printing time (normal mode)" | "total estimated time" => {
                keep(&mut self.time, Some(value.to_owned()));
            }
            // Cura: seconds.
            "time" => keep(&mut self.time, value.parse::<f64>().ok().map(duration)),
            "total filament used [g]" | "filament used [g]" | "total filament weight [g]" => {
                keep(
                    &mut self.grams,
                    sum(value).map(|g| format!("{} g", short(g))),
                );
            }
            "filament used [mm]" | "total filament length [mm]" => keep(
                &mut self.length,
                sum(value).map(|mm| format!("{} m", short(mm / 1000.))),
            ),
            // Cura: metres, with their unit.
            "filament used" => keep(
                &mut self.length,
                sum(value).map(|m| format!("{} m", short(m))),
            ),
            "layer_height" | "layer height" => keep(
                &mut self.layer_height,
                value
                    .parse::<f64>()
                    .ok()
                    .map(|mm| format!("{} mm", short(mm))),
            ),
            "total layer number" | "total layers count" | "layer_count" => {
                keep(&mut self.layers, Some(value.to_owned()));
            }
            "printer_model" | "target_machine.name" => {
                keep(&mut self.printer, Some(value.to_owned()));
            }
            "filament_type" => keep(&mut self.material, Some(value.to_owned())),
            _ => {}
        }
    }

    /// A comment's text, after its `;`.
    fn comment(&mut self, text: &str) {
        let text = text.trim();
        // `generated by PrusaSlicer 2.8.1 on 2024-10-21 at 06:38:01 UTC`
        if let Some(rest) = text.strip_prefix("generated by ") {
            let name = rest.split(" on ").next().unwrap_or(rest);
            self.note("producer", name);
            return;
        }
        if let Some(rest) = text.strip_prefix("Generated with ") {
            self.note("producer", &rest.replace("Cura_SteamEngine", "Cura"));
            return;
        }
        // Bambu Studio's header names itself on a line of its own.
        if text.starts_with("BambuStudio ") {
            self.note("producer", text);
            return;
        }
        // Several facts on one line: `model printing time: 1m; total
        // estimated time: 2m`.
        for part in text.split("; ") {
            let split = match (part.find('='), part.find(':')) {
                (Some(eq), Some(colon)) => Some(eq.min(colon)),
                (eq, colon) => eq.or(colon),
            };
            if let Some(at) = split {
                self.note(&part[..at], &part[at + 1..]);
            }
        }
    }

    fn into_details(self) -> Vec<(String, String)> {
        [
            ("Print time", self.time),
            ("Filament", self.grams),
            ("Filament length", self.length),
            ("Material", self.material),
            ("Layer height", self.layer_height),
            ("Layers", self.layers),
            ("Printer", self.printer),
            ("Sliced with", self.slicer),
        ]
        .into_iter()
        .filter_map(|(label, value)| Some((label.to_owned(), value?)))
        .collect()
    }
}

/// A picture a comment block holds, and its size as the block says.
struct Stored {
    area: u64,
    base64: String,
}

/// The pictures between `; <tag> begin W×H length` and `; <tag> end`,
/// the largest kept; a block the read cut is not one.
fn largest(lines: &[&str]) -> Option<Stored> {
    let mut best: Option<Stored> = None;
    let mut open: Option<(String, Stored)> = None;
    for line in lines {
        let Some(text) = line.strip_prefix(';') else {
            continue;
        };
        let words: Vec<&str> = text.split_whitespace().collect();
        match (&mut open, words.as_slice()) {
            (None, [tag, "begin", size, ..]) if is_picture(tag) => {
                let Some(area) = size
                    .split_once(['x', '*'])
                    .and_then(|(w, h)| Some(w.parse::<u64>().ok()? * h.parse::<u64>().ok()?))
                else {
                    continue;
                };
                open = Some((
                    (*tag).to_owned(),
                    Stored {
                        area,
                        base64: String::new(),
                    },
                ));
            }
            (Some((tag, _)), [end_tag, "end"]) if end_tag == tag => {
                let Some((_, stored)) = open.take() else {
                    continue;
                };
                if best.as_ref().is_none_or(|b| stored.area > b.area) {
                    best = Some(stored);
                }
            }
            (Some((_, stored)), [data]) => stored.base64.push_str(data),
            _ => {}
        }
    }
    best
}

/// A comment block's tag that holds a picture: `thumbnail`,
/// `thumbnail_JPG`, `thumbnail_QOI`, and the `png`/`jpg` of some firmware.
fn is_picture(tag: &str) -> bool {
    let tag = tag.to_ascii_lowercase();
    tag.starts_with("thumbnail") || tag == "png" || tag == "jpg"
}

/// G-code as text: its first `TEXT_INPUT` bytes for the pictures and the
/// facts written first, its last `TAIL` for those written last.
pub fn text(path: &Path, side: u32, cancel: &CancelToken) -> anyhow::Result<Found> {
    let mut file = inspection::open(path)?;
    let len = file.metadata()?.len();
    let mut head = Vec::new();
    (&mut file)
        .take(limits::TEXT_INPUT as u64)
        .read_to_end(&mut head)?;
    inspection::check(cancel)?;
    let head = String::from_utf8_lossy(&head);
    let lines: Vec<&str> = head.lines().collect();
    let mut facts = Facts::default();
    for line in &lines {
        if let Some(comment) = line.strip_prefix(';') {
            facts.comment(comment);
        }
    }
    if len > head.len() as u64 {
        let from = len.saturating_sub(TAIL).max(head.len() as u64);
        file.seek(SeekFrom::Start(from))?;
        let mut tail = Vec::new();
        file.take(TAIL).read_to_end(&mut tail)?;
        // The first line may be cut: it is left out.
        let tail = String::from_utf8_lossy(&tail);
        for line in tail.lines().skip(1) {
            if let Some(comment) = line.strip_prefix(';') {
                facts.comment(comment);
            }
        }
    }
    let mut picture = largest(&lines).and_then(|stored| {
        let bytes = base64::engine::general_purpose::STANDARD
            .decode(stored.base64)
            .ok()?;
        crate::decoded(&bytes, side)
    });
    let mut details = facts.into_details();
    // No picture stored: the moves drawn.
    if picture.is_none()
        && let Some(drawn) = crate::toolpath::draw(path, side, cancel)?
    {
        picture = Some(drawn.picture);
        details.extend(drawn.details);
    }
    Ok(Found {
        title: "G-code".into(),
        picture,
        details,
        notice: None,
    })
}

/// Blocks read before giving up on finding the G-code: metadata and a
/// picture per size come first, a few dozen at most.
const BLOCKS: usize = 64;

/// Prusa's binary G-code: a header (`GCDE`, version, checksum kind), then
/// blocks of metadata and pictures, then blocks of G-code. Metadata is
/// `key=value` lines, stored as is or deflated.
pub fn binary(path: &Path, side: u32, cancel: &CancelToken) -> anyhow::Result<Found> {
    let mut file = std::io::BufReader::new(inspection::open(path)?);
    let mut header = [0u8; 10];
    file.read_exact(&mut header)?;
    anyhow::ensure!(&header[..4] == b"GCDE", "Not a binary G-code file");
    let u16_at = |bytes: &[u8], at: usize| u16::from_le_bytes([bytes[at], bytes[at + 1]]);
    let u32_at = |bytes: &[u8], at: usize| {
        u32::from_le_bytes([bytes[at], bytes[at + 1], bytes[at + 2], bytes[at + 3]])
    };
    let checksum = if u16_at(&header, 8) == 1 { 4 } else { 0 };
    let mut facts = Facts::default();
    let mut best: Option<(u64, Vec<u8>)> = None;
    for _ in 0..BLOCKS {
        inspection::check(cancel)?;
        let mut head = [0u8; 12];
        if file.read_exact(&mut head[..8]).is_err() {
            break;
        }
        let (kind, compression) = (u16_at(&head, 0), u16_at(&head, 2));
        let stored = if compression == 0 {
            u32_at(&head, 4)
        } else {
            file.read_exact(&mut head[8..12])?;
            u32_at(&head, 8)
        };
        // G-code from here on: everything wanted came before.
        if kind == 1 {
            break;
        }
        let mut parameters = [0u8; 6];
        let parameters = &mut parameters[..if kind == 5 { 6 } else { 2 }];
        file.read_exact(parameters)?;
        let wanted = matches!(kind, 0 | 3 | 4 | 5) && matches!(compression, 0 | 1);
        if !wanted || stored as usize > limits::BINARY_INPUT {
            file.seek_relative(i64::from(stored) + checksum)?;
            continue;
        }
        let mut data = vec![0u8; stored as usize];
        file.read_exact(&mut data)?;
        file.seek_relative(checksum)?;
        if compression == 1 {
            let mut inflated = Vec::new();
            flate2::read::ZlibDecoder::new(data.as_slice())
                .take(limits::BINARY_INPUT as u64)
                .read_to_end(&mut inflated)?;
            data = inflated;
        }
        if kind == 5 {
            let area = u64::from(u16_at(parameters, 2)) * u64::from(u16_at(parameters, 4));
            if best.as_ref().is_none_or(|(b, _)| area > *b) {
                best = Some((area, data));
            }
        } else {
            for line in String::from_utf8_lossy(&data).lines() {
                if let Some((key, value)) = line.split_once('=') {
                    facts.note(key, value);
                }
            }
        }
    }
    Ok(Found {
        title: "Binary G-code".into(),
        picture: best.and_then(|(_, bytes)| crate::decoded(&bytes, side)),
        details: facts.into_details(),
        notice: None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fmt::Write as _;
    use std::io::Write as _;

    /// A picture of `width` × `height`, one colour, as PNG.
    fn png(width: u32, height: u32) -> Vec<u8> {
        let mut bytes = Vec::new();
        image::RgbaImage::from_pixel(width, height, image::Rgba([200, 100, 0, 255]))
            .write_to(
                &mut std::io::Cursor::new(&mut bytes),
                image::ImageFormat::Png,
            )
            .unwrap();
        bytes
    }

    /// A picture block as `PrusaSlicer` writes it: base64 in lines of 78.
    fn block(tag: &str, width: u32, height: u32) -> String {
        let encoded = base64::engine::general_purpose::STANDARD.encode(png(width, height));
        let mut out = format!(";\n; {tag} begin {width}x{height} {}\n", encoded.len());
        for line in encoded.as_bytes().chunks(78) {
            let _ = writeln!(out, "; {}", std::str::from_utf8(line).unwrap());
        }
        let _ = write!(out, "; {tag} end\n;\n");
        out
    }

    #[test]
    fn a_slicers_picture_and_facts() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("a part’s print.gcode");
        let mut text =
            String::from("; generated by PrusaSlicer 2.8.1 on 2024-10-21 at 06:38:01 UTC\n");
        text.push_str("; printer_model = MK4S\n; filament used [g] = 0.75, 0.25\n");
        text.push_str(&block("thumbnail", 16, 16));
        text.push_str(&block("thumbnail_QOI", 32, 18));
        // A block the read would cut is not taken.
        text.push_str("; thumbnail begin 640x480 999\n; AAAA\n");
        text.push_str("G1 X10 Y10 E0.5\n".repeat(20000).as_str());
        text.push_str("; estimated printing time (normal mode) = 1h 2m 3s\n");
        text.push_str("; filament_type = PLA\n; layer_height = 0.20\n");
        std::fs::write(&path, &text).unwrap();
        let found = super::text(&path, 256, &CancelToken::new()).unwrap();
        let picture = found.picture.expect("the largest picture");
        assert_eq!((picture.width, picture.height), (32, 18));
        let details: Vec<(&str, &str)> = found
            .details
            .iter()
            .map(|(l, v)| (l.as_str(), v.as_str()))
            .collect();
        assert_eq!(
            details,
            [
                ("Print time", "1h 2m 3s"),
                ("Filament", "1 g"),
                ("Material", "PLA"),
                ("Layer height", "0.2 mm"),
                ("Printer", "MK4S"),
                ("Sliced with", "PrusaSlicer 2.8.1"),
            ]
        );
    }

    #[test]
    fn cura_and_bambu_say_it_their_way() {
        let dir = tempfile::tempdir().unwrap();
        let cura = dir.path().join("cura.gcode");
        std::fs::write(
            &cura,
            ";FLAVOR:Marlin\n;TIME:3725\n;Filament used: 1.23456m\n;Layer height: 0.12\n;LAYER_COUNT:80\n;TARGET_MACHINE.NAME:Creality Ender-3\n;Generated with Cura_SteamEngine 5.6.0\nG28\n",
        )
        .unwrap();
        let found = super::text(&cura, 256, &CancelToken::new()).unwrap();
        assert!(found.picture.is_none());
        let get = |found: &Found, label: &str| {
            found
                .details
                .iter()
                .find(|(l, _)| l == label)
                .map(|(_, v)| v.clone())
        };
        assert_eq!(get(&found, "Print time").as_deref(), Some("1h 2m 5s"));
        assert_eq!(get(&found, "Filament length").as_deref(), Some("1.23 m"));
        assert_eq!(get(&found, "Layer height").as_deref(), Some("0.12 mm"));
        assert_eq!(get(&found, "Layers").as_deref(), Some("80"));
        assert_eq!(get(&found, "Printer").as_deref(), Some("Creality Ender-3"));
        assert_eq!(get(&found, "Sliced with").as_deref(), Some("Cura 5.6.0"));
        let bambu = dir.path().join("bambu.gcode");
        std::fs::write(
            &bambu,
            "; HEADER_BLOCK_START\n; BambuStudio 01.09.00.70\n; model printing time: 50m 3s; total estimated time: 56m 9s\n; total layer number: 50\n; total filament weight [g] : 3.21\n; HEADER_BLOCK_END\n",
        )
        .unwrap();
        let found = super::text(&bambu, 256, &CancelToken::new()).unwrap();
        assert_eq!(get(&found, "Print time").as_deref(), Some("56m 9s"));
        assert_eq!(get(&found, "Filament").as_deref(), Some("3.21 g"));
        assert_eq!(get(&found, "Layers").as_deref(), Some("50"));
        assert_eq!(
            get(&found, "Sliced with").as_deref(),
            Some("BambuStudio 01.09.00.70")
        );
    }

    /// A binary G-code block: header, parameters, data, CRC.
    fn binary_block(kind: u16, deflate: bool, parameters: &[u8], data: &[u8]) -> Vec<u8> {
        let mut out = kind.to_le_bytes().to_vec();
        if deflate {
            let mut encoder =
                flate2::write::ZlibEncoder::new(Vec::new(), flate2::Compression::fast());
            encoder.write_all(data).unwrap();
            let packed = encoder.finish().unwrap();
            out.extend(1u16.to_le_bytes());
            out.extend(u32::try_from(data.len()).unwrap().to_le_bytes());
            out.extend(u32::try_from(packed.len()).unwrap().to_le_bytes());
            out.extend(parameters);
            out.extend(packed);
        } else {
            out.extend(0u16.to_le_bytes());
            out.extend(u32::try_from(data.len()).unwrap().to_le_bytes());
            out.extend(parameters);
            out.extend(data);
        }
        out.extend([0; 4]);
        out
    }

    #[test]
    fn binary_gcode_blocks() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("a part’s print.bgcode");
        let mut file = b"GCDE".to_vec();
        file.extend(1u32.to_le_bytes());
        file.extend(1u16.to_le_bytes());
        let ini = 0u16.to_le_bytes();
        file.extend(binary_block(
            0,
            false,
            &ini,
            b"Producer=PrusaSlicer 2.8.1\n",
        ));
        file.extend(binary_block(
            3,
            false,
            &ini,
            b"printer_model=MK4S\nfilament_type=PETG\n",
        ));
        for (width, height) in [(16u16, 16u16), (48, 27)] {
            let mut parameters = 0u16.to_le_bytes().to_vec();
            parameters.extend(width.to_le_bytes());
            parameters.extend(height.to_le_bytes());
            file.extend(binary_block(
                5,
                false,
                &parameters,
                &png(u32::from(width), u32::from(height)),
            ));
        }
        file.extend(binary_block(
            4,
            true,
            &ini,
            b"estimated printing time (normal mode)=3m 41s\nfilament used [g]=0.75\n",
        ));
        file.extend(binary_block(1, false, &ini, b"G28\n"));
        std::fs::write(&path, &file).unwrap();
        let found = binary(&path, 256, &CancelToken::new()).unwrap();
        let picture = found.picture.expect("the largest picture");
        assert_eq!((picture.width, picture.height), (48, 27));
        let labels: Vec<&str> = found.details.iter().map(|(l, _)| l.as_str()).collect();
        assert_eq!(
            labels,
            [
                "Print time",
                "Filament",
                "Material",
                "Printer",
                "Sliced with"
            ]
        );
        assert_eq!(found.details[0].1, "3m 41s");
        assert_eq!(found.details[4].1, "PrusaSlicer 2.8.1");
    }
}
